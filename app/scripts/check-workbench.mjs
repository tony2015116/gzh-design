import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { createApplication } from '../../server/application.mjs';
const require = createRequire(new URL('../../server/package.json', import.meta.url));
const { default: puppeteer } = await import(pathToFileURL(require.resolve('puppeteer-core')).href);
const dataDir = await mkdtemp(join(tmpdir(), 'gzh-workbench-ui-'));
const output = resolve('../output/workbench-ui');
await mkdir(output, { recursive: true });
let app, server, browser;
try {
  app = await createApplication({ dataDir, staticDir: resolve('dist'), publicUrl: 'http://localhost', config: { AI_FORMAT_LOG_LEVEL: 'off' } });
  server = createServer(app.handle);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  browser = await puppeteer.launch({ executablePath: process.env.BROWSER_EXECUTABLE_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage();
  await browser.defaultBrowserContext().overridePermissions(origin, ['clipboard-read', 'clipboard-write']);
  page.setDefaultTimeout(8000);
  page.on('dialog', dialog => void dialog.accept());
  const errors = [];
  const providerRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/showdoc|cimi|lowfans|10w\/articles/.test(request.url())) providerRequests.push(request.url()); });
  await page.setViewport({ width: 1600, height: 1050, deviceScaleFactor: 1.25 });
  await page.goto(origin, { waitUntil: 'networkidle0' });
  await page.waitForSelector('.workbench-shell', { timeout: 1500 });
  assert.match(await page.$eval('body', el => el.innerText), /把内容写好/);
  assert.equal(await page.$eval('[data-preview-frame]', el => Math.round(el.getBoundingClientRect().width)), 375);
  const articleBeforeSkin = await page.$eval('#wechat-article-preview', el => ({ html: el.innerHTML, background: getComputedStyle(el).backgroundColor }));
  assert.equal(await page.$('.wb-actions .wb-skin-toggle'), null, 'Skin selection belongs in settings, not article actions');
  const changeSkin = async skin => {
    const settingsButtons = await page.$$('[aria-label="工作台设置"]');
    const settingsButton = await (async () => { for (const button of settingsButtons) if (await button.isVisible()) return button; })();
    assert.ok(settingsButton, 'A visible settings entry is required');
    await settingsButton.click();
    await page.waitForSelector('[data-skin-settings]');
    await page.click(`[aria-label="切换至${skin === 'dark' ? '暗黑' : '明亮'}皮肤"]`);
    if (skin === 'dark' && page.viewport().width >= 1000) await page.screenshot({ path: join(output, '09-skin-settings.png'), fullPage: true });
    await page.click('[aria-label="关闭工作台设置"]');
    await page.waitForSelector('[data-skin-settings]', { hidden: true });
  };
  await changeSkin('dark');
  await page.waitForFunction(() => document.documentElement.dataset.appSkin === 'dark');
  assert.equal(await page.$eval('#wechat-article-preview', el => getComputedStyle(el).backgroundColor), articleBeforeSkin.background);
  assert.equal(await page.$eval('#wechat-article-preview', el => el.innerHTML), articleBeforeSkin.html);
  const editorDark = await page.$eval('textarea', el => ({ background: getComputedStyle(el).backgroundColor, color: getComputedStyle(el).color }));
  assert.notEqual(editorDark.background, 'rgb(255, 255, 255)');
  await page.screenshot({ path: join(output, '06-dark-skin.png'), fullPage: true });
  await page.click('[aria-label="选择整套风格方案"]');
  assert.notEqual(await page.$eval('.wb-control-popover', el => getComputedStyle(el).backgroundColor), 'rgb(255, 255, 255)');
  await page.keyboard.press('Escape');
  await page.reload({ waitUntil: 'networkidle0' });
  assert.equal(await page.evaluate(() => document.documentElement.dataset.appSkin), 'dark');
  await changeSkin('light');
  await page.waitForFunction(() => document.documentElement.dataset.appSkin === 'light');
  await page.screenshot({ path: join(output, '01-desktop.png'), fullPage: true });
  const normalEditorBox = await page.$eval('.wb-editor-grid', el => ({ width: el.clientWidth, height: el.clientHeight }));
  const originalMarkdown = await page.$eval('textarea', el => el.value);
  await page.click('[aria-label="进入专注全屏"]');
  await page.waitForSelector('.workbench-shell.is-focus-mode');
  await page.waitForFunction(() => !document.querySelector('.wb-focus-toggle')?.disabled);
  await changeSkin('dark');
  assert.equal(await page.$eval('.workbench-shell', el => el.classList.contains('is-focus-mode')), true);
  await page.screenshot({ path: join(output, '07-dark-focus.png'), fullPage: true });
  await changeSkin('light');
  const focusedEditorBox = await page.$eval('.wb-editor-grid', el => ({ width: el.clientWidth, height: el.clientHeight }));
  assert.ok(focusedEditorBox.width > normalEditorBox.width && focusedEditorBox.height > normalEditorBox.height);
  assert.equal(await page.$eval('.wb-sidebar', el => getComputedStyle(el).display), 'none');
  const nativeFullscreen = await page.evaluate(() => document.fullscreenElement === document.documentElement);
  await page.screenshot({ path: join(output, '05-focus-fullscreen.png'), fullPage: true });
  await page.click('[data-action="image-export"]');
  await page.waitForFunction(() => document.body.innerText.includes('完整长图'));
  assert.equal(await page.$eval('.workbench-shell', el => el.classList.contains('is-focus-mode')), true);
  await page.click('button[title="关闭"]');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('.workbench-shell.is-focus-mode'));
  await page.click('[aria-label="进入专注全屏"]');
  await page.waitForFunction(() => !document.querySelector('.wb-focus-toggle')?.disabled);
  await page.click('[aria-label="退出专注全屏"]');
  await page.waitForFunction(() => !document.querySelector('.workbench-shell.is-focus-mode'));
  await page.evaluate(() => { document.documentElement.requestFullscreen = async () => { throw new Error('test_fullscreen_unavailable'); }; });
  await page.click('[aria-label="进入专注全屏"]');
  await page.waitForSelector('.workbench-shell.is-focus-mode');
  await page.waitForFunction(() => !document.querySelector('.wb-focus-toggle')?.disabled);
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => !document.querySelector('.workbench-shell.is-focus-mode'));
  await page.evaluate(() => { delete document.documentElement.requestFullscreen; });
  assert.equal(await page.$eval('textarea', el => el.value), originalMarkdown);
  await page.click('[aria-label="爆文发现，二期规划"]');
  await page.waitForSelector('dialog[aria-labelledby="roadmap-title"]');
  await page.waitForFunction(() => document.querySelector('dialog')?.open === true);
  const dialogBox = await page.$eval('dialog', el => { const r = el.getBoundingClientRect(); return { centerX: r.x + r.width / 2, centerY: r.y + r.height / 2 }; });
  assert.ok(Math.abs(dialogBox.centerX - 800) < 3 && Math.abs(dialogBox.centerY - 525) < 3, JSON.stringify(dialogBox));
  await page.screenshot({ path: join(output, '04-roadmap.png'), fullPage: true });
  assert.equal(providerRequests.length, 0);
  await page.keyboard.press('Escape');
  await page.waitForSelector('dialog[aria-labelledby="roadmap-title"]', { hidden: true, timeout: 2000 });
  const markdown = '# 工作台验证\n\n这是需要保存的测试文章。\n\n## 第一步\n\n**保留原有排版能力。**';
  await page.$eval('textarea', (el, text) => { const setter = Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set; setter.call(el, text); el.dispatchEvent(new Event('input', { bubbles: true })); }, markdown);
  await page.evaluate(() => { window.__workbenchNavigationCheck = true; });
  await page.click('.wb-brand');
  assert.equal(await page.evaluate(() => window.__workbenchNavigationCheck), true);
  assert.equal(await page.$eval('textarea', el => el.value), markdown);
  await page.waitForFunction(() => localStorage.getItem('gzh_editor_draft')?.includes('工作台验证'));
  await page.reload({ waitUntil: 'networkidle0' });
  assert.equal(await page.$eval('textarea', el => el.value), markdown);
  await page.click('.wb-copy-action');
  const clipboard = await page.evaluate(async () => {
    const items = await navigator.clipboard.read();
    const item = items.find(item => item.types.includes('text/html'));
    return item ? await (await item.getType('text/html')).text() : '';
  });
  assert.match(clipboard, /工作台验证/);
  assert.match(clipboard, /style=/);
  await page.click('.wb-preview-tabs [role="tab"]:nth-child(2)');
  await page.waitForFunction(() => document.body.innerText.includes('Thread'));
  await page.click('.wb-preview-tabs [role="tab"]:first-child');
  await page.click('[aria-label="预览宽度"]');
  await page.select('[aria-label="预览宽度"]', '677');
  assert.equal(await page.$eval('[data-preview-frame]', el => Math.round(el.getBoundingClientRect().width)), 677);
  await page.select('[aria-label="预览宽度"]', '375');
  await page.click('[data-action="image-export"]');
  await page.waitForFunction(() => document.body.innerText.includes('完整长图'));
  await page.waitForFunction(() => [...document.querySelectorAll('img[alt^="Generated export"]')].some(image => image.naturalWidth > 0));
  const exported = await page.$eval('img[alt^="Generated export"]', el => ({ src: el.src, width: el.naturalWidth }));
  assert.equal(exported.width, 750);
  await writeFile(join(output, 'export-result.png'), Buffer.from(exported.src.split(',')[1], 'base64'));
  await page.screenshot({ path: join(output, '02-export.png'), fullPage: true });
  await page.click('button[title="关闭"]');
  const importPath = join(dataDir, 'import.md');
  await writeFile(importPath, '# 本地导入验证\n\n导入后可撤销，保留先前草稿。');
  const fileInput = await page.$('input[type="file"][accept=".md,.markdown,.txt"]');
  await fileInput.uploadFile(importPath);
  await page.waitForFunction(() => document.querySelector('textarea')?.value.includes('本地导入验证'));
  await page.click('.wb-actions [aria-haspopup="menu"]');
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent.includes('撤销：')));
  await page.evaluate(() => [...document.querySelectorAll('button')].find(button => button.textContent.includes('撤销：')).click());
  assert.equal(await page.$eval('textarea', el => el.value), markdown);
  await page.goto(origin, { waitUntil: 'networkidle0' });
  await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1 });
  await page.screenshot({ path: join(output, '03-mobile.png'), fullPage: true });
  await changeSkin('dark');
  await page.waitForFunction(() => document.documentElement.dataset.appSkin === 'dark');
  await page.screenshot({ path: join(output, '08-dark-mobile.png'), fullPage: true });
  await changeSkin('light');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.click('[aria-label="进入专注全屏"]');
  await page.waitForSelector('.workbench-shell.is-focus-mode');
  await page.waitForFunction(() => !document.querySelector('.wb-focus-toggle')?.disabled);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.click('[aria-label="退出专注全屏"]');
  await page.waitForFunction(() => !document.querySelector('.workbench-shell.is-focus-mode'));
  await page.click('[aria-label="选择整套风格方案"]');
  const popover = await page.$eval('.wb-control-popover', el => { const box = el.getBoundingClientRect(); return { left: box.left, right: box.right }; });
  assert.ok(popover.left >= 0 && popover.right <= 390, JSON.stringify(popover));
  await page.keyboard.press('Escape');
  await page.click('.wb-mobile-navigation [aria-haspopup="menu"]');
  assert.match(await page.$eval('.wb-mobile-navigation', el => el.innerText), /视频对比/);
  assert.match(await page.$eval('.wb-mobile-navigation', el => el.innerText), /配置与诊断/);
  await page.keyboard.press('Escape');
  await page.evaluate(async () => {
    const response = await fetch('/api/auth/register', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'ui@example.test', password: 'Workbench-test-1234' }) });
    const data = await response.json();
    if (!response.ok) throw new Error(JSON.stringify(data));
    localStorage.setItem('auth_token', data.token);
    localStorage.setItem('auth_user', JSON.stringify(data.user));
  });
  await page.reload({ waitUntil: 'networkidle0' });
  await page.click('.wb-mobile-navigation [aria-haspopup="menu"]');
  assert.match(await page.$eval('.wb-mobile-navigation', el => el.innerText), /退出登录/);
  await page.evaluate(() => [...document.querySelectorAll('.wb-mobile-navigation button')].find(button => button.textContent.trim() === '退出登录').click());
  await page.waitForFunction(() => !localStorage.getItem('auth_token'));
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log(JSON.stringify({ desktop: 'PASS', mobile: 'PASS', uiSkinPersistence: 'PASS', articleSkinIndependent: 'PASS', darkPopover: 'PASS', darkFullscreen: 'PASS', darkMobile: 'PASS', focusFullscreen: 'PASS', nativeFullscreen, fullscreenFallback: 'PASS', fullscreenExport: 'PASS', draftRestore: 'PASS', sameRouteNavigation: 'PASS', importUndo: 'PASS', richClipboard: 'PASS', previewWidths: 'PASS', roadmap: 'PASS', imageExportWidth: exported.width, mobilePopover: 'PASS', mobileNavigationAndLogout: 'PASS', pageErrors: errors, providerRequests }));
} finally {
  await browser?.close();
  if (server?.listening) await new Promise(resolve => server.close(resolve));
  await app?.close();
  await rm(dataDir, { recursive: true, force: true });
  console.log('Owned test server and browser closed');
}
